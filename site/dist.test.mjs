// Checks the built site (`just site-build`, which `just site-test` runs
// first): the LLM notice is the page banner exactly where the page's
// source has the notice, and is not also left in the page body.
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";
import { DOCS, LLM_NOTICE, NOTICE_LINK, PAGES, llmNotice, pageId } from "./links.mjs";

const root = new URL("..", import.meta.url);
const files = [
  ...Object.keys(PAGES),
  ...readdirSync(new URL(DOCS, root))
    .filter((n) => n.endsWith(".md"))
    .map((n) => `${DOCS}${n}`),
];

function text(html) {
  return html
    .replace(/<[^>]*>/g, "")
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();
}

const banners = (html) => [...html.matchAll(/<div[^>]*\bdata-llm-notice\b[^>]*>([\s\S]*?)<\/div>/g)];
const built = (file) => readFileSync(new URL(`site/dist/${file}`, root), "utf8");

test("LLM notice banner", () => {
  const plain = text(LLM_NOTICE.replace(`[${NOTICE_LINK.text}](${NOTICE_LINK.href})`, NOTICE_LINK.text));
  for (const file of files) {
    const id = pageId(file);
    const html = built(`${id === "" ? "" : `${id}/`}index.html`);
    const found = banners(html);
    const notice = llmNotice(readFileSync(new URL(file, root), "utf8"));
    if (notice === null) {
      assert.equal(found.length, 0, `${file}: banner without a notice in the source`);
      continue;
    }
    assert.equal(found.length, 1, `${file}: one banner`);
    assert.equal(text(found[0][1]), `${plain}${notice && ` ${notice}`}`, `${file}: banner text`);
    assert.ok(found[0][1].includes(`href="${NOTICE_LINK.href}"`), `${file}: banner link`);
    // The banner is the only place the notice appears: no body blockquote.
    assert.equal(text(html).split(plain).length - 1, 1, `${file}: notice in the body too`);
    assert.doesNotMatch(html, /<blockquote>\s*<p>This text was generated by an LLM/, `${file}: notice blockquote in the body`);
  }
  // The landing page has the notice, and docs/hive.md context after it.
  assert.equal(llmNotice(readFileSync(new URL("site/index.mdx", root), "utf8")), "", "landing page notice");
  assert.ok(llmNotice(readFileSync(new URL("docs/hive.md", root), "utf8")), "docs/hive.md notice context");
  // Every rendered document has the notice today; Starlight's 404 page
  // has no source and so no notice, and shows no banner.
  assert.equal(banners(built("404.html")).length, 0, "404 page: banner without a notice");
});
